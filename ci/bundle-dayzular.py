#!/usr/bin/env python3
"""Generate src/TraderXDayZular: a copy of DayZular that ships inside TraderX.

Server owners then need only CF + TraderX. When the standalone DayZular mod is loaded too,
its config defines DAYZULAR and every file of this copy compiles to nothing
(`#ifndef DAYZULAR`), so the classes are never declared twice and the standalone wins.

Rules:
  - The copy must be the PUBLISHED DayZular, and that DayZular must already define DAYZULAR
    (CfgMods defines[]). A server running an older standalone without the define would
    compile both copies and fail with duplicate classes - publish DayZular first.
  - Do not edit src/TraderXDayZular by hand: rerun this script after DayZular changes.

  ci/bundle-dayzular.py [DAYZULAR_SRC]     (default: ../DayZular/src/DayZular)
"""
import os
import re
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                      os.environ.get("DAYZULAR_SRC", os.path.join(REPO, "..", "DayZular", "src", "DayZular")))
DST = os.path.join(REPO, "src", "TraderXDayZular")
PREFIX = "TraderXDayZular"
GUARD = "DAYZULAR"

HEADER = ("// GENERATED by ci/bundle-dayzular.py from DayZular - do not edit.\n"
          "// Compiled out when the standalone DayZular mod (which defines DAYZULAR) is loaded.\n")


def rewrite_paths(text):
    # asset paths of the copy live under its own PBO prefix
    return re.sub(r'DayZular([/\\])(gui|scripts)\1', lambda m: PREFIX + m.group(1) + m.group(2) + m.group(1), text)


def main():
    cfg_path = os.path.join(SRC, "config.cpp")
    if not os.path.isfile(cfg_path):
        sys.exit(f"DayZular source not found: {SRC}")
    cfg = open(cfg_path, encoding="utf-8").read()
    if not re.search(r'defines\[\]\s*=\s*\{[^}]*"' + GUARD + '"', cfg):
        sys.exit(f"{cfg_path} does not define {GUARD}: add defines[]={{\"{GUARD}\"}} to its CfgMods class and publish it first")

    if os.path.isdir(DST):
        shutil.rmtree(DST)
    os.makedirs(DST)

    files = 0
    for sub in ("scripts", "gui"):
        root = os.path.join(SRC, sub)
        for dirpath, _, names in os.walk(root):
            for name in sorted(names):
                src = os.path.join(dirpath, name)
                rel = os.path.relpath(src, SRC)
                dst = os.path.join(DST, rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                if name.endswith(".c"):
                    body = rewrite_paths(open(src, encoding="utf-8-sig").read())
                    with open(dst, "w", encoding="utf-8", newline="\n") as f:
                        f.write(f"{HEADER}#ifndef {GUARD}\n{body}\n#endif\n")
                elif name.endswith(".layout"):
                    with open(dst, "w", encoding="utf-8", newline="\n") as f:
                        f.write(rewrite_paths(open(src, encoding="utf-8-sig").read()))
                else:
                    shutil.copy2(src, dst)
                files += 1

    # config: own CfgPatches/CfgMods names, own script paths, and no DAYZULAR define (that
    # define means "the standalone is loaded")
    out = cfg.replace('class DayZular_Script', 'class TraderX_DayZular')
    out = re.sub(r'(class\s+CfgMods\s*\{\s*class\s+)DayZular\b', r'\1' + PREFIX, out)
    out = re.sub(r'\bdir\s*=\s*"DayZular"', f'dir="{PREFIX}"', out)
    out = re.sub(r'\bname\s*=\s*"DayZular"', 'name="DayZular (bundled with TraderX)"', out)
    out = re.sub(r'[ \t]*//[^\n]*\n(?=[ \t]*//[^\n]*\n[ \t]*defines\[\])', '', out)
    out = re.sub(r'[ \t]*//[^\n]*\n[ \t]*defines\[\][^;]*;\n', '', out)
    out = re.sub(r'[ \t]*defines\[\][^;]*;\n', '', out)
    out = rewrite_paths(out)
    with open(os.path.join(DST, "config.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by ci/bundle-dayzular.py from DayZular - do not edit.\n" + out)
    with open(os.path.join(DST, "$PBOPREFIX$"), "w", newline="\n") as f:
        f.write(PREFIX)
    for extra in ("LICENSE.md",):
        if os.path.isfile(os.path.join(SRC, extra)):
            shutil.copy2(os.path.join(SRC, extra), os.path.join(DST, extra))
    print(f"TraderXDayZular: {files} files from {SRC}")


if __name__ == "__main__":
    main()
